package ru.skypro.homework.service;

import ru.skypro.homework.dto.Register;

/**
 * Интерфейс сервиса аутентификации и регистрации пользователей.
 * <p>
 * Определяет контракт для базовых операций:
 * - аутентификация пользователя (login);
 * - регистрация нового пользователя (register).
 * </p>
 */
public interface AuthService {

    /**
     * Выполняет аутентификацию пользователя по логину и паролю.
     * <p>
     * В рамках проекта логин соответствует email пользователя.
     * </p>
     *
     * @param userName логин пользователя (email)
     * @param password пароль пользователя в открытом виде
     * @return true, если аутентификация успешна; false — в противном случае
     */
    boolean login(String userName, String password);

    /**
     * Регистрирует нового пользователя в системе.
     * <p>
     * Проверяет уникальность учётных данных (email), хеширует пароль
     * и сохраняет пользователя в базе данных.
     * </p>
     *
     * @param register DTO с данными для регистрации (email, пароль, ФИО, телефон и т. п.)
     * @return true при успешной регистрации; false, если пользователь уже существует или произошла ошибка
     */
    boolean register(Register register);
}
