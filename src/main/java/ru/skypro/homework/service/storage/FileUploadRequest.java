package ru.skypro.homework.service.storage;

import java.io.InputStream;

/**
 * DTO‑запрос для загрузки файла в хранилище.
 * <p>
 * Содержит все необходимые метаданные и само содержимое файла.
 * Поле {@code directory} предусмотрено для масштабируемости (например, для S3 или локальной ФС),
 * но в текущей реализации с Alfresco может игнорироваться.
 * </p>
 */
public record FileUploadRequest(
        /**
         * Директория/префикс для хранения файла.
         * <p>
         * Используется в хранилищах с иерархией (S3, локальная ФС).
         * В интеграции с Alfresco может не применяться — файл размещается согласно логике репозитория.
         * </p>
         */
        String directory,

        /**
         * Имя файла (включая расширение).
         */
        String fileName,

        /**
         * MIME‑тип содержимого (например, image/png, application/pdf).
         */
        String contentType,

        /**
         * Размер файла в байтах.
         */
        long size,

        /**
         * Поток с содержимым файла.
         * <p>
         * Важно: поток должен быть читаемым в момент обработки запроса.
         * Не гарантируется, что его можно будет перечитать повторно.
         * </p>
         */
        InputStream content
) {
}
