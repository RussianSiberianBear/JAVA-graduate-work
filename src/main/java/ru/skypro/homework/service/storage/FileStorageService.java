package ru.skypro.homework.service.storage;

/**
 * Интерфейс сервиса для работы с файловым хранилищем.
 * <p>
 * Определяет базовый контракт для операций загрузки, получения информации,
 * скачивания и удаления файлов, а также проверки их существования.
 * Реализация может работать с локальным диском, S3‑совместимым хранилищем,
 * FTP или любым другим источником — это скрыто за данным интерфейсом.
 * </p>
 */
public interface FileStorageService {

    /**
     * Загружает файл в хранилище.
     * <p>
     * Принимает запрос на загрузку, сохраняет файл и возвращает метаданные
     * в виде {@link StoredFileInfo}. При ошибке выбрасывается соответствующее
     * исключение (зависит от реализации).
     * </p>
     *
     * @param request запрос на загрузку файла ({@link FileUploadRequest})
     * @return объект с информацией о сохранённом файле ({@link StoredFileInfo})
     */
    StoredFileInfo upload(FileUploadRequest request);

    /**
     * Получает метаданные файла по его идентификатору.
     * <p>
     * Возвращает только информацию о файле (имя, размер, тип, дата загрузки и т. п.)
     * без самого содержимого. Если файл не найден, может выбрасывать исключение
     * или возвращать null — зависит от реализации.
     * </p>
     *
     * @param fileId идентификатор файла в хранилище
     * @return метаданные файла ({@link StoredFileInfo})
     */
    StoredFileInfo getInfo(String fileId);

    /**
     * Получает содержимое файла по его идентификатору.
     * <p>
     * Возвращает объект {@link StoredFile}, который включает как метаданные,
     * так и само содержимое (например, в виде byte[] или InputStream).
     * Если файл не найден, поведение зависит от реализации (исключение или null).
     * </p>
     *
     * @param fileId идентификатор файла в хранилище
     * @return объект с содержимым и метаданными файла ({@link StoredFile})
     */
    StoredFile get(String fileId);

    /**
     * Удаляет файл из хранилища по его идентификатору.
     * <p>
     * Операция необратима. Если файл не существует, может выбрасываться
     * исключение либо игнорироваться — зависит от реализации.
     * Используется совместно с {@link FileReplacementCoordinator} для
     * гарантированного удаления «старых» или «сиротских» файлов после транзакции.
     * </p>
     *
     * @param fileId идентификатор файла для удаления
     */
    void delete(String fileId);

    /**
     * Проверяет, существует ли файл в хранилище по его идентификатору.
     * <p>
     * Быстрый способ убедиться в наличии файла без загрузки его содержимого
     * или полных метаданных. Возвращает true, если файл найден, иначе false.
     * </p>
     *
     * @param fileId идентификатор файла
     * @return true, если файл существует; false — если нет
     */
    boolean exists(String fileId);
}
