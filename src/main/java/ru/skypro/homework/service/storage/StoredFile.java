package ru.skypro.homework.service.storage;

/**
 * DTO, объединяющий метаданные и содержимое загруженного файла.
 * <p>
 * Используется, когда сервису требуется одновременно информация о файле
 * (имя, тип, размер и т. п.) и его содержимое (в виде массива байтов).
 * </p>
 */
public record StoredFile(
        /**
         * Метаданные файла ({@link StoredFileInfo}): идентификатор, имя, тип, размер, дата загрузки и т. д.
         */
        StoredFileInfo info,

        /**
         * Содержимое файла в виде массива байтов.
         * <p>
         * Подходит для небольших файлов. Для больших файлов предпочтительнее
         * использовать {@code InputStream} вместо загрузки всего содержимого в память.
         * </p>
         */
        byte[] content
) {
}
