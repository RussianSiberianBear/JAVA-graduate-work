package ru.skypro.homework.service.storage;

/**
 * DTO с метаданными сохранённого файла.
 * <p>
 * Содержит ключевую информацию о файле без его содержимого:
 * идентификатор, имя, тип (MIME), размер.
 * Используется для отображения списка файлов, валидации, логирования,
 * а также как часть других DTO (например, в {@link StoredFile}).
 * </p>
 */
public record StoredFileInfo(
        /**
         * Уникальный идентификатор файла в хранилище.
         */
        String id,

        /**
         * Имя файла (включая расширение).
         */
        String fileName,

        /**
         * MIME‑тип содержимого (например, image/png, application/pdf).
         */
        String contentType,

        /**
         * Размер файла в байтах.
         */
        long size
) {
}
