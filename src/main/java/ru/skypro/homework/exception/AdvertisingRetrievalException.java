package ru.skypro.homework.exception;

/**
 * Исключение, возникающее при ошибках получения (чтения) объявления.
 * <p>
 * Используется в сервисе и контроллере при обработке сценариев, когда невозможно
 * получить данные объявления — например, из‑за проблем с доступом к хранилищу,
 * ошибок чтения из базы данных, временных сбоев или иных технических проблем.
 * В отличие от {@link AdvertisingNotFoundException}, это исключение сигнализирует
 * не об отсутствии записи, а о проблеме при попытке её прочитать.
 * Является непроверяемым (RuntimeException), поэтому не требует обязательного
 * перехвата в try‑catch на уровне вызывающего кода. Обычно такое исключение
 * сопоставляют с HTTP‑ответом 500 Internal Server Error.
 * </p>
 */
public class AdvertisingRetrievalException extends RuntimeException {

    /**
     * Создаёт исключение с указанным сообщением.
     *
     * @param message описание ошибки (например, «Не удалось получить объявление с ID 123»)
     */
    public AdvertisingRetrievalException(String message) {
        super(message);
    }

    /**
     * Создаёт исключение с указанным сообщением и причиной.
     * <p>
     * Позволяет сохранить стек вызова и детали исходного исключения — это полезно
     * для отладки и логирования.
     * </p>
     *
     * @param message описание ошибки
     * @param cause   исходное исключение, ставшее причиной ошибки
     */
    public AdvertisingRetrievalException(String message, Throwable cause) {
        super(message, cause);
    }
}
