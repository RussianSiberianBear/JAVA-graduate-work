package ru.skypro.homework.exception;

/**
 * Исключение, возникающее при ошибках работы с хранилищем файлов.
 * <p>
 * Используется в сервисе и контроллере при обработке сценариев, когда невозможно
 * выполнить операции с файлами — например, сохранить, прочитать или удалить файл
 * из хранилища (локальной файловой системы, S3‑совместимого хранилища и т. п.).
 * Возможные причины: отсутствие доступа к директории, нехватка места, неверный путь,
 * ошибки сетевого взаимодействия с внешним хранилищем.
 * Является непроверяемым (RuntimeException), поэтому не требует обязательного
 * перехвата в try‑catch на уровне вызывающего кода. Обычно такое исключение
 * сопоставляют с HTTP‑ответом 500 Internal Server Error.
 * </p>
 */
public class FileStorageException extends RuntimeException {

    /**
     * Создаёт исключение с указанным сообщением.
     *
     * @param message описание ошибки (например, «Не удалось сохранить файл: нет доступа к директории»)
     */
    public FileStorageException(String message) {
        super(message);
    }

    /**
     * Создаёт исключение с указанным сообщением и причиной.
     * <p>
     * Позволяет сохранить стек вызова и детали исходного исключения — это полезно
     * для отладки и логирования.
     * </p>
     *
     * @param message описание ошибки
     * @param cause   исходное исключение, ставшее причиной ошибки
     */
    public FileStorageException(String message, Throwable cause) {
        super(message, cause);
    }
}
