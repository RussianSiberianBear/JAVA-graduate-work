package ru.skypro.homework.exception;

/**
 * Исключение, возникающее при ошибках, связанных с некорректным паролем.
 * <p>
 * Используется в сервисе и контроллере при обработке сценариев, когда пароль
 * не соответствует требованиям системы — например, не проходит проверку сложности,
 * не совпадает с текущим паролем при смене или не удовлетворяет бизнес‑правилам.
 * Является непроверяемым (RuntimeException), поэтому не требует обязательного
 * перехвата в try‑catch на уровне вызывающего кода. Обычно такое исключение
 * сопоставляют с HTTP‑ответом 400 Bad Request.
 * </p>
 */
public class InvalidPasswordException extends RuntimeException {

    /**
     * Создаёт исключение с указанным сообщением.
     *
     * @param message описание ошибки (например, «Пароль не соответствует требованиям сложности»
     *                или «Пароли не совпадают»)
     */
    public InvalidPasswordException(String message) {
        super(message);
    }
}
