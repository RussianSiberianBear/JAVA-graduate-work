package ru.skypro.homework.exception;

/**
 * Исключение, возникающее при ошибках обновления объявления.
 * <p>
 * Используется в сервисе и контроллере при обработке сценариев, когда обновление
 * объявления невозможно — например, из‑за некорректных данных, нарушения бизнес‑правил
 * (например, запрещено менять цену после публикации), отсутствия записи (в этом случае
 * предпочтительнее {@link AdvertisingNotFoundException}) или технических проблем.
 * Является непроверяемым (RuntimeException), поэтому не требует обязательного
 * перехвата в try‑catch на уровне вызывающего кода. Обычно такое исключение
 * сопоставляют с HTTP‑ответом 400 Bad Request или 500 Internal Server Error
 * в зависимости от характера ошибки.
 * </p>
 */
public class AdvertisingUpdateException extends RuntimeException {

    /**
     * Создаёт исключение с указанным сообщением.
     *
     * @param message описание ошибки (например, «Не удалось обновить объявление: недопустимая цена»)
     */
    public AdvertisingUpdateException(String message) {
        super(message);
    }

    /**
     * Создаёт исключение с указанным сообщением и причиной.
     * <p>
     * Позволяет сохранить стек вызова и детали исходного исключения — это полезно
     * для отладки и логирования.
     * </p>
     *
     * @param message описание ошибки
     * @param cause   исходное исключение, ставшее причиной ошибки
     */
    public AdvertisingUpdateException(String message, Throwable cause) {
        super(message, cause);
    }
}
