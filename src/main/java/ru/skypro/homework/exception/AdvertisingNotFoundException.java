package ru.skypro.homework.exception;

/**
 * Исключение, возникающее, когда запрашиваемое объявление не найдено.
 * <p>
 * Используется в сервисе и контроллере при обработке сценариев, когда операция
 * (получение, обновление, удаление и т. п.) не может быть выполнена из‑за отсутствия
 * объявления с указанным идентификатором. Является непроверяемым (RuntimeException),
 * поэтому не требует обязательного перехвата в try‑catch на уровне вызывающего кода.
 * Обычно такое исключение сопоставляют с HTTP‑ответом 404 Not Found.
 * </p>
 */
public class AdvertisingNotFoundException extends RuntimeException {

    /**
     * Создаёт исключение с указанным сообщением.
     *
     * @param message описание ошибки (например, «Объявление с ID 123 не найдено»)
     */
    public AdvertisingNotFoundException(String message) {
        super(message);
    }
}
