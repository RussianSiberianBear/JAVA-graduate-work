package ru.skypro.homework.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * DTO для создания или обновления комментария.
 * <p>
 * Используется в запросах к контроллеру при добавлении нового комментария
 * или редактировании существующего. Содержит только поле с текстом комментария,
 * для которого заданы ограничения по длине (от 8 до 64 символов).
 * </p>
 */
@Schema(description = "DTO одного комментария при создании или обновлении")
public record CommentRequestDto(

        /**
         * Текст комментария.
         * Должен содержать от 8 до 64 символов.
         * Пример: Мой комментарий к объявлению
         */
        @Schema(description = "Текст комментария",
                example = "Мой комментарий к объявлению",
                minLength = 8,
                maxLength = 64)
        String text
) {
}
