package ru.skypro.homework.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;

/**
 * DTO для частичного обновления данных пользователя.
 * <p>
 * Используется в PATCH‑запросе к эндпоинту /users/me. Позволяет обновить
 * отдельные поля профиля (имя, фамилию, телефон) без необходимости передачи
 * всех данных пользователя. Поля помечены как nullable — можно передавать
 * только те значения, которые требуется изменить. Валидация выполняется
 * с помощью аннотаций Jakarta Validation.
 * </p>
 */
@Schema(description = "Запрос на обновление данных пользователя (частичное обновление)")
public record UserUpdateInfoDto(

        /**
         * Имя пользователя.
         * Необязательное поле: можно не передавать, если не требуется обновление.
         * Длина: от 2 до 32 символов; допускаются только буквы, пробелы и дефисы.
         * Пример: John
         */
        @Schema(description = "Имя пользователя",
                example = "John",
                minLength = 2,
                maxLength = 32,
                pattern = "^[A-Za-zА-Яа-я\\s-]+$",
                nullable = true)
        @Size(min = 2, max = 32, message = "Имя должно содержать от 2 до 32 символов")
        @Pattern(regexp = "^[A-Za-zА-Яа-я\\s-]+$",
                message = "Имя может содержать только буквы, пробелы и дефисы")
        String firstName,

        /**
         * Фамилия пользователя.
         * Необязательное поле: можно не передавать, если не требуется обновление.
         * Длина: от 2 до 32 символов; допускаются только буквы, пробелы и дефисы.
         * Пример: Doe
         */
        @Schema(description = "Фамилия пользователя",
                example = "Doe",
                minLength = 2,
                maxLength = 32,
                pattern = "^[A-Za-zА-Яа-я\\s-]+$",
                nullable = true)
        @Size(min = 2, max = 32, message = "Фамилия должна содержать от 2 до 32 символов")
        @Pattern(regexp = "^[A-Za-zА-Яа-я\\s-]+$",
                message = "Фамилия может содержать только буквы, пробелы и дефисы")
        String lastName,

        /**
         * Номер телефона пользователя.
         * Необязательное поле: можно не передавать, если не требуется обновление.
         * Должен содержать от 10 до 20 символов, может начинаться с «+»,
         * допускаются цифры, пробелы, дефисы и скобки.
         * Пример: +7 (999) 123-45-67
         */
        @Schema(description = "Номер телефона пользователя",
                example = "+7 (999) 123-45-67",
                pattern = "^\\+?[0-9\\s\\-()]{10,20}$",
                nullable = true)
        @Pattern(regexp = "^\\+?[0-9\\s\\-()]{10,20}$",
                message = "Телефон должен содержать от 10 до 20 цифр, может начинаться с +")
        String phone
) {
}
